import { flushPromises, mount } from '@vue/test-utils';
import { afterEach, describe, expect, it, vi } from 'vitest';
import LogisticsManagementView from './LogisticsManagementView.vue';
import { createMockLogisticsService } from './mockLogisticsService';
import { currentUser } from '../../services/authSession';
import type {LoginResult} from '../../types/auth';
import { clearMessages,messages } from '../../components/feedback/message';
import { newTemplate } from './templateRules';
const permissions=(codes:string[])=>{currentUser.value={permissions:codes} as LoginResult;};
afterEach(()=>{currentUser.value=null;clearMessages();});
describe('logistics management',()=>{
  it('lists companies and separates account/template writes from company access',async()=>{
    permissions(['logistics:view']);const service=createMockLogisticsService();
    await service.createCompany({code:'A',name:'合作甲',provider:'MANUAL',status:'disabled',contactName:'',contactPhone:'',sortOrder:0,remark:'',version:0});
    const wrapper=mount(LogisticsManagementView,{props:{service}});await flushPromises();
    expect(wrapper.text()).toContain('合作甲');expect(wrapper.find('[data-testid="company-new"]').exists()).toBe(false);
    await wrapper.get('[data-testid="company-configure-1"]').trigger('click');await flushPromises();
    expect(wrapper.find('[data-testid="account-tab"]').exists()).toBe(false);
    expect(wrapper.find('[data-testid="company-form"]').exists()).toBe(false);
    wrapper.unmount();
  });
  it('creates, edits and changes cooperation status with Message feedback',async()=>{
    permissions(['logistics:view','logistics:edit']);const service=createMockLogisticsService();
    const wrapper=mount(LogisticsManagementView,{props:{service}});await flushPromises();
    await wrapper.get('[data-testid="company-new"]').trigger('click');
    await wrapper.get('[name="company-name"]').setValue('合作甲');await wrapper.get('[name="company-code"]').setValue('A');
    await wrapper.get('[data-testid="company-form"]').trigger('submit');await flushPromises();
    expect(messages.value.some(m=>m.text==='公司资料已保存')).toBe(true);
    await wrapper.get('[data-testid="company-back"]').trigger('click');await flushPromises();
    await wrapper.get('[data-testid="company-status-1"]').trigger('click');
    await wrapper.get('[data-testid="status-confirm"]').trigger('click');await flushPromises();
    expect((await service.getCompany(1)).status).toBe('enabled');
    expect(messages.value.some(m=>m.text==='合作状态已更新')).toBe(true);
    wrapper.unmount();
  });
  it('refreshes the backend company version after account save before editing company details',async()=>{
    permissions(['logistics:view','logistics:edit','logistics:configure']);const service=createMockLogisticsService();
    const company=await service.createCompany({code:'A',name:'合作甲',provider:'MANUAL',status:'disabled',contactName:'',contactPhone:'',sortOrder:0,remark:'',version:0});
    // Mirror the real backend independently of the mock's account implementation.
    let parentVersion=company.version;
    const saveAccount=service.saveAccount;
    service.saveAccount=async(id,input)=>{const saved=await saveAccount(id,input);parentVersion++;return saved;};
    const getCompany=service.getCompany;
    service.getCompany=async id=>({...await getCompany(id),version:parentVersion});
    const updateCompany=vi.fn(async(_id,input)=>{
      if(input.version!==parentVersion)throw new Error('记录已更新，请刷新后重试');
      return {...company,...input,version:parentVersion+1};
    });service.updateCompany=updateCompany;
    const wrapper=mount(LogisticsManagementView,{props:{service}});await flushPromises();
    await wrapper.get('[data-testid="company-configure-1"]').trigger('click');
    await wrapper.get('[data-testid="account-tab"]').trigger('click');await flushPromises();
    await wrapper.get('[data-testid="account-form"]').trigger('submit');await flushPromises();
    await wrapper.get('nav button').trigger('click');await flushPromises();
    await wrapper.get('[name="company-name"]').setValue('修改后公司');
    await wrapper.get('[data-testid="company-form"]').trigger('submit');await flushPromises();
    expect(updateCompany).toHaveBeenCalledWith(1,expect.objectContaining({version:parentVersion,name:'修改后公司'}));
    expect(wrapper.text()).not.toContain('记录已更新');
    wrapper.unmount();
  });
  it('reports account success separately when the following company refresh fails and recovers via retry',async()=>{
    permissions(['logistics:view','logistics:edit','logistics:configure']);const service=createMockLogisticsService();
    await service.createCompany({code:'A',name:'合作甲',provider:'MANUAL',status:'disabled',contactName:'',contactPhone:'',sortOrder:0,remark:'',version:0});
    const realGet=service.getCompany;const getCompany=vi.fn().mockRejectedValueOnce(new Error('读取暂不可用')).mockImplementation(realGet);service.getCompany=getCompany;
    const saveAccount=vi.spyOn(service,'saveAccount');
    const wrapper=mount(LogisticsManagementView,{props:{service}});await flushPromises();
    await wrapper.get('[data-testid="company-configure-1"]').trigger('click');
    await wrapper.get('[data-testid="account-tab"]').trigger('click');await flushPromises();
    await wrapper.get('[data-testid="account-form"]').trigger('submit');await flushPromises();
    expect(messages.value.some(m=>m.type==='success'&&m.text==='接口及寄件资料已保存')).toBe(true);
    expect(wrapper.text()).toContain('账号已保存，但公司资料刷新失败');
    expect(messages.value.some(m=>m.type==='error')).toBe(false);
    await wrapper.get('nav button').trigger('click');await flushPromises();
    expect(wrapper.get('[data-testid="company-form"] fieldset').attributes('disabled')).toBeDefined();
    await wrapper.get('[data-testid="account-metadata-retry"]').trigger('click');await flushPromises();
    expect(wrapper.find('[data-testid="account-metadata-retry"]').exists()).toBe(false);
    expect(wrapper.get('[data-testid="company-form"] fieldset').attributes('disabled')).toBeUndefined();
    expect(saveAccount).toHaveBeenCalledTimes(1);expect(getCompany).toHaveBeenCalledTimes(2);
    wrapper.unmount();
  });
  it('saves and reloads HuiSen pickup settings on the existing Yimi account',async()=>{
    permissions(['logistics:view','logistics:configure']);const service=createMockLogisticsService();
    const company=await service.createCompany({code:'PICKUP',name:'汇森合作物流',provider:'YIMI',status:'disabled',contactName:'',contactPhone:'',sortOrder:0,remark:'',version:0});
    const account=await service.saveAccount(company.id,{version:0,code:'',customerCode:'',dictId:'',orderUrl:'',appKey:'private-key',appSecret:'private-secret',yimi:{sellerId:'seller',subscriptionId:'subscription'},sender:{name:'',phone:'',province:'',city:'',county:'',address:''}});
    const wrapper=mount(LogisticsManagementView,{props:{service}});await flushPromises();
    await wrapper.get(`[data-testid="company-configure-${company.id}"]`).trigger('click');
    await wrapper.get('[data-testid="account-tab"]').trigger('click');await flushPromises();
    await wrapper.get('[name="designatedPickup"]').setValue(true);
    await wrapper.get('[name="salesmanCode"]').setValue('00123');
    await wrapper.get('[name="salesmanName"]').setValue('揽收员甲');
    await wrapper.get('[data-testid="account-form"]').trigger('submit');await flushPromises();
    const saved=await service.getAccount(company.id);
    expect(saved).toMatchObject({id:account.id,appKeyConfigured:true,appSecretConfigured:true,ready:false,yimi:{designatedPickup:true,salesmanCode:'00123',salesmanName:'揽收员甲'}});
    expect(wrapper.get('[name="designatedPickup"]').element).toHaveProperty('checked',true);
    expect(wrapper.get('[name="salesmanCode"]').element).toHaveProperty('value','00123');
    expect(wrapper.get('[name="appKey"]').element).toHaveProperty('value','');
    expect(wrapper.get('[name="appSecret"]').element).toHaveProperty('value','');
    expect(messages.value.some(m=>m.text==='接口及寄件资料已保存')).toBe(true);
    expect(wrapper.text()).toContain('本地测试数据，不支持真实接口下单');
    wrapper.unmount();
  });
  it('displays catalog province names for saved template codes while preserving unknown origin values',async()=>{
    permissions(['logistics:view']);const service=createMockLogisticsService();
    const company=await service.createCompany({code:'A',name:'合作甲',provider:'MANUAL',status:'disabled',contactName:'',contactPhone:'',sortOrder:0,remark:'',version:0});
    await service.createTemplate(company.id,{...newTemplate(),name:'代码省份合同',originProvince:'330000',originCity:'金华市',originCounty:'义乌市'});
    await service.createTemplate(company.id,{...newTemplate(),name:'待修正合同',originProvince:'未知省',originCity:'',originCounty:''});
    const wrapper=mount(LogisticsManagementView,{props:{service}});await flushPromises();
    await wrapper.get('[data-testid="company-configure-1"]').trigger('click');
    await wrapper.findAll('nav button')[1].trigger('click');await flushPromises();
    const rows=wrapper.findAll('tbody tr');
    expect(rows[0].findAll('td')[1].text()).toBe('浙江省 金华市 义乌市');
    expect(rows[1].findAll('td')[1].text()).toBe('未知省');
    wrapper.unmount();
  });
});
